# グレードの読み
def format_grade_text_and_reading(grade_str):
    g = grade_str.upper().strip()
    if "5" in g:
        return "グレード5", "グレードご"
    elif "4" in g:
        return "グレード4", "グレードよん"
    elif "3" in g:
        return "グレード3", "グレードさん"
    elif "2" in g:
        return "グレード2", "グレードに"
    elif "1" in g:
        return "グレード1", "グレードいち"
    elif "0" in g:
        return "グレード0", "グレードゼロ"
    return "グレード5", "グレードご"

def get_base_motion(title):
    t = re.sub(r'\(.*?\)|［.*?］', '', title).strip()
    return t

def main():
    with open('data/cards.json', 'r', encoding='utf-8') as f:
        cards = json.load(f)

    updated_count = 0

    for c in cards:
        title = c.get('title', '')
        pos = c.get('pos', '端座位')
        grade = c.get('grade', 'G5/4/3')
        muscle_orig = c.get('muscle', '')
        base_motion = get_base_motion(title)

        # マッチする臨床ヒントを探す
        matched_hint = None
        for key in sorted(CLINICAL_HINTS.keys(), key=lambda x: -len(x)):
            if key in base_motion:
                matched_hint = CLINICAL_HINTS[key]
                break

        # 臨床ヒント（上級：第1句）
        if matched_hint:
            c['kami_adv'] = matched_hint['adv']
            c['kami_std'] = matched_hint['std']
            muscle_short = matched_hint['muscle_short']
        else:
            # フォールバック
            c['kami_adv'] = f"{c.get('nerve', '運動神経')}障害、近隣筋の代償動作を警戒しつつ……"
            c['kami_std'] = f"{base_motion}を観察する臨床テスト……"
            # 筋肉名の先頭部分を取得
            muscle_clean = re.sub(r'（.*?）', '', muscle_orig).split('・')[0].strip()
            muscle_short = muscle_clean or "主動作筋"

        # 第2句（体位 ＋ Grade）
        grade_text, grade_reading = format_grade_text_and_reading(grade)
        pos_base = pos.split('（')[0].strip()
        pos_read = POS_READINGS.get(pos, POS_READINGS.get(pos_base, pos_base))

        c['naka_short'] = f"{pos_base}で、{grade_text}。"
        c['naka_reading'] = f"{pos_read}で、{grade_reading}。"

        # 第3句（筋肉名）
        c['shimo_short'] = f"{muscle_short}。"
        c['shimo_reading'] = f"{muscle_short}。"

        updated_count += 1

    with open('data/cards.json', 'w', encoding='utf-8') as f:
        json.dump(cards, f, ensure_ascii=False, indent=2)

    print(f"✅ 全 {updated_count} 枚のカードに初級/上級句および第2句(体位+Grade)・第3句(筋肉名)を付与しました！")

if __name__ == '__main__':
    main()
